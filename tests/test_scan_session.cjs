const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('src/markdown_to_handwrite/webui/app.js', 'utf8');
const code = source.slice(source.indexOf('function persistScanSession()'), source.indexOf('function readDraft()'));
const storage = new Map();
const button = (key, value) => ({dataset: {[key]: value}, classList: {toggle() {}}, setAttribute() {}});
const controls = {'[data-scan-mode]': [button('scanMode', 'smart'), button('scanMode', 'bw')], '[data-scan-orientation]': [button('scanOrientation','auto')], '[data-scan-format]': [button('scanFormat','jpg')]};
const context = {SCAN_SESSION_KEY:'scan', state:{scanPages:[{scanId:'0123456789abcdef',url:'/preview',processed:true,marks:[{kind:'comment',text:'hello'}],filterPreviews:{smart:'temporary'}}],scanPage:0,scanMode:'bw',scanOrientation:'auto',scanFormat:'jpg'}, localStorage:{setItem:(k,v)=>storage.set(k,v),getItem:k=>storage.get(k)}, $$: selector=>controls[selector]};
vm.createContext(context); vm.runInContext(code, context);
context.persistScanSession();
context.state.scanPages=[]; context.state.scanMode='smart';
context.restoreScanSession();
assert.equal(context.state.scanPages[0].marks[0].text,'hello');
assert.equal(context.state.scanMode,'bw');
assert.equal(context.state.scanPages[0].filterPreviewKey,null);
context.state.scanPages=[]; context.persistScanSession(); context.restoreScanSession();
assert.equal(context.state.scanPages.length,0);
console.log('Scan session recovery checks passed');
